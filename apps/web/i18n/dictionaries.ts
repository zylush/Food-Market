export type Dictionary = { [Key in keyof (typeof dictionaries)["en"]]: string };
export type TranslationKey = keyof Dictionary;

export function isSupportedLocale(value: string): value is Locale {
  return Object.prototype.hasOwnProperty.call(dictionaries, value);
}

export function getDictionary(locale: string): Dictionary {
  return isSupportedLocale(locale) ? dictionaries[locale] : dictionaries.en;
}

export function translate(locale: string, key: TranslationKey, variables: Record<string, string | number> = {}): string {
  let message = getDictionary(locale)[key];
  for (const [name, value] of Object.entries(variables)) {
    message = message.replace(`{${name}}`, String(value));
  }
  return message;
}
